const assert=require('node:assert/strict')
const fs=require('node:fs')
const {DatabaseSync}=require('node:sqlite')
const db=new DatabaseSync(':memory:')
db.exec('PRAGMA foreign_keys=ON')
db.exec(fs.readFileSync('migrations/0002_employees.sql','utf8'))
db.prepare('INSERT INTO employees(id,name,job_title,email,password_hash,active,created_at) VALUES(?,?,?,?,?,?,?)').run('employee','Employee','Developer','test@example.com','hash',1,0)
db.prepare('INSERT INTO attendance VALUES(?,?,?,?,?)').run('night','employee','2026-10-18',100,200)
db.prepare('INSERT INTO attendance VALUES(?,?,?,?,?)').run('open','employee','2026-10-19',300,null)
const legacy=db.prepare('SELECT * FROM attendance ORDER BY id').all()
db.exec(fs.readFileSync('migrations/0011_employee_multiple_shifts.sql','utf8').replace(/\r?\n/g,' '))
assert.deepEqual(db.prepare('SELECT * FROM attendance_shifts ORDER BY id').all(),legacy)
assert.deepEqual(db.prepare('SELECT * FROM attendance ORDER BY id').all(),legacy)
assert.throws(()=>db.prepare('INSERT INTO attendance_shifts VALUES(?,?,?,?,?)').run('duplicate-open','employee','2026-10-19',400,null),/UNIQUE/)
db.prepare('UPDATE attendance_shifts SET check_out=400 WHERE id=?').run('open')
db.prepare('INSERT INTO attendance_shifts VALUES(?,?,?,?,?)').run('evening','employee','2026-10-19',500,null)
assert.equal(db.prepare('SELECT count(*) AS n FROM attendance_shifts WHERE day=?').get('2026-10-19').n,2)
assert.throws(()=>db.prepare('INSERT INTO attendance_shifts VALUES(?,?,?,?,?)').run('bad-time','employee','2026-10-20',700,600),/CHECK/)
db.close()
console.log('Shift migration passed: original records preserved, historical table retained, multiple same-day shifts allowed, one open shift enforced.')
